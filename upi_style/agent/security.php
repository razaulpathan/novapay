<?php
// agent/security.php - Promoter Security (Google 2FA configuration)
require_once '../db.php';

// Auth check
if (!isLoggedIn()) {
    header("Location: login.php");
    exit;
}

// Fetch agent details
$stmt = $pdo->prepare("SELECT * FROM users WHERE id = ?");
$stmt->execute([$_SESSION['user_id']]);
$user = $stmt->fetch();

if (!$user || $user['status'] === 'Blocked') {
    session_destroy();
    header("Location: login.php");
    exit;
}

$error_msg = '';
$success_msg = '';

// Generate Google 2FA secret if not yet assigned
if (empty($user['google_2fa_secret'])) {
    $new_secret = Google2FA::generateSecret();
    $stmtUpdate = $pdo->prepare("UPDATE users SET google_2fa_secret = ? WHERE id = ?");
    $stmtUpdate->execute([$new_secret, $user['id']]);
    
    // Refresh user cache
    $user['google_2fa_secret'] = $new_secret;
}

// Handle 2FA status toggling
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action']) && $_POST['action'] === 'toggle_2fa') {
    $verify_code = isset($_POST['verify_code']) ? trim($_POST['verify_code']) : '';
    
    if (empty($verify_code)) {
        $error_msg = "Please enter the 6-digit authenticator code.";
    } else {
        // Validate code
        if (Google2FA::verifyCode($user['google_2fa_secret'], $verify_code)) {
            $new_state = ($user['google_2fa_enabled'] == 1) ? 0 : 1;
            
            $stmtToggle = $pdo->prepare("UPDATE users SET google_2fa_enabled = ? WHERE id = ?");
            $stmtToggle->execute([$new_state, $user['id']]);
            
            $user['google_2fa_enabled'] = $new_state;
            $success_msg = $new_state ? "Google 2FA has been successfully enabled!" : "Google 2FA has been successfully disabled!";
        } else {
            $error_msg = "Invalid verification code. Please check your authenticator app.";
        }
    }
}

// Include Layout Header
$current_page = 'security.php';
require_once 'header.php';
?>

