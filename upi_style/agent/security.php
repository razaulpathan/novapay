    <?php endif; ?>
    
    <?php if (!empty($success_msg)): ?>
      <div class="security-alert alert-success"><?= sanitize($success_msg) ?></div>
    <?php endif; ?>

    <div class="security-flex-container">
      <div class="security-details-section">
        <h3>Secure Your Account</h3>
        <p>Two-factor authentication adds an extra layer of security to your promoter profile. To login, you will be required to provide your password as well as a 6-digit TOTP code generated by your mobile authenticator app (such as Google Authenticator, Authy, or Microsoft Authenticator).</p>
        
        <div class="status-box-2fa">
          <span>Current Status:</span>
          <?php if ($user['google_2fa_enabled'] == 1): ?>
            <span class="status-badge-active">ENABLED</span>
          <?php else: ?>
            <span class="status-badge-inactive">DISABLED</span>
          <?php endif; ?>
        </div>

        <form method="POST" class="toggle-2fa-form">
          <input type="hidden" name="action" value="toggle_2fa">
          <div class="form-input-group">
            <label class="form-input-label" for="verify_code">Enter Authenticator Verification Code</label>
            <div style="display: flex; gap: 12px; width: 100%;">
              <input type="text" name="verify_code" id="verify_code" class="form-text-input" placeholder="e.g. 123456" pattern="\d{6}" maxlength="6" required style="letter-spacing: 2px; font-weight: 700; text-align: center;">
              <button type="submit" class="submit-action-btn <?= ($user['google_2fa_enabled'] == 1) ? 'btn-danger-theme' : 'btn-success-theme' ?>">
                <?= ($user['google_2fa_enabled'] == 1) ? 'Disable 2FA' : 'Enable 2FA' ?>
              </button>
            </div>
          </div>
        </form>
      </div>

      <div class="security-setup-section">
        <div class="setup-steps-title">Manual Setup Guidelines</div>
        <ol class="setup-steps-list">
          <li>Download an Authenticator app on your smartphone.</li>
          <li>Choose "Add account" -> "Enter key manually".</li>
          <li>Enter the following account details:
            <div class="key-box">
              <span class="key-label">Account Name:</span>
              <span class="key-value">NextPay:<?= sanitize($user['phone']) ?></span>
            </div>
            <div class="key-box">
              <span class="key-label">Secret Key:</span>
              <span class="key-value secret-key-copy" id="secret-key-span"><?= sanitize($user['google_2fa_secret']) ?></span>
            </div>
          </li>
          <li>Copy the code generated by the app, paste it on the verification box, and submit.</li>
        </ol>
      </div>
    </div>

  </div>
</div>

