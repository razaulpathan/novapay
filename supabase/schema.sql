-- 1. Create Enums
DO $$ BEGIN
  CREATE TYPE user_role AS ENUM ('user', 'agent', 'sub_admin', 'admin');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
  CREATE TYPE order_status AS ENUM ('Pending', 'Success', 'Cancelled');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
  CREATE TYPE payout_status AS ENUM ('Paying', 'Success', 'Failed');
EXCEPTION
  WHEN duplicate_object THEN null;
END $$;

-- 2. Users Table
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone VARCHAR(20) UNIQUE NOT NULL,
  password VARCHAR(255) NOT NULL,
  name VARCHAR(100) DEFAULT 'Nova User',
  itoken_balance NUMERIC(15,2) DEFAULT 0.00,
  today_profit NUMERIC(15,2) DEFAULT 0.00,
  reward_rate NUMERIC(5,2) DEFAULT 2.50,
  auto_selling BOOLEAN DEFAULT TRUE,
  order_min INT DEFAULT 100,
  order_max INT DEFAULT 50000,
  referred_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  referral_code VARCHAR(20) UNIQUE NOT NULL,
  role user_role DEFAULT 'user',
  status VARCHAR(20) DEFAULT 'Active',
  google_2fa_enabled BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. UPI Accounts Table (Linked payout UPI handles)
CREATE TABLE IF NOT EXISTS public.upi_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
  partner VARCHAR(50) NOT NULL,
  name VARCHAR(100) NOT NULL,
  upi_no VARCHAR(100) NOT NULL,
  is_default BOOLEAN DEFAULT FALSE,
  status VARCHAR(20) DEFAULT 'Active',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Buy Orders Table (Deposits with UTR)
CREATE TABLE IF NOT EXISTS public.buy_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no VARCHAR(40) UNIQUE NOT NULL,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
  type VARCHAR(20) NOT NULL DEFAULT 'UPI',
  price NUMERIC(15,2) NOT NULL,
  reward NUMERIC(15,2) NOT NULL DEFAULT 0.00,
  itokens NUMERIC(15,2) NOT NULL DEFAULT 0.00,
  status order_status DEFAULT 'Pending',
  utr VARCHAR(100),
  cancel_reason TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Sell Orders Table (Withdrawals)
CREATE TABLE IF NOT EXISTS public.sell_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
  amount NUMERIC(15,2) NOT NULL,
  upi_no VARCHAR(100) NOT NULL,
  partner VARCHAR(50) DEFAULT 'UPI',
  status payout_status DEFAULT 'Paying',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Token Transfers Table (Agent Wallet to Downline User)
CREATE TABLE IF NOT EXISTS public.token_transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
  target_phone VARCHAR(20) NOT NULL,
  target_uid BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  amount NUMERIC(15,2) NOT NULL,
  status order_status DEFAULT 'Success',
  note TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Commission Payouts Table
CREATE TABLE IF NOT EXISTS public.commission_payouts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  earner_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
  source_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
  level INT NOT NULL DEFAULT 1,
  amount NUMERIC(15,2) NOT NULL,
  order_no VARCHAR(40),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Global Settings Table
CREATE TABLE IF NOT EXISTS public.settings (
  setting_key VARCHAR(100) PRIMARY KEY,
  setting_value TEXT NOT NULL DEFAULT ''
);

-- 9. Announcements Table
CREATE TABLE IF NOT EXISTS public.announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  body TEXT NOT NULL,
  badge VARCHAR(50) DEFAULT 'NEWS',
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Support Tickets Table
CREATE TABLE IF NOT EXISTS public.support_tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
  subject VARCHAR(255) NOT NULL,
  message TEXT NOT NULL,
  status VARCHAR(20) DEFAULT 'Open',
  reply TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

