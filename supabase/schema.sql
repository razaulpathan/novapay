-- 12. Helper Trigger Function: Auto-credit balance when deposit is marked Success
CREATE OR REPLACE FUNCTION public.handle_buy_order_success()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.status = 'Success' AND OLD.status != 'Success' THEN
    UPDATE public.users
    SET itoken_balance = itoken_balance + NEW.itokens,
        updated_at = NOW()
    WHERE id = NEW.user_id;

    -- Award Level 1 Commission to referrer if exists
    DECLARE
      v_referrer_id BIGINT;
      v_commission_amount NUMERIC(15,2);
    BEGIN
      SELECT referred_by INTO v_referrer_id FROM public.users WHERE id = NEW.user_id;
      IF v_referrer_id IS NOT NULL THEN
        v_commission_amount := ROUND((NEW.price * 0.015), 2);
        UPDATE public.users 
        SET itoken_balance = itoken_balance + v_commission_amount,
            today_profit = today_profit + v_commission_amount
        WHERE id = v_referrer_id;

        INSERT INTO public.commission_payouts (earner_id, source_id, level, amount, order_no)
        VALUES (v_referrer_id, NEW.user_id, 1, v_commission_amount, NEW.order_no);
      END IF;
    END;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_buy_order_success ON public.buy_orders;
CREATE TRIGGER trg_buy_order_success
AFTER UPDATE ON public.buy_orders
FOR EACH ROW
EXECUTE FUNCTION public.handle_buy_order_success();
